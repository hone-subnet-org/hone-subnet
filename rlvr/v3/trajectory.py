from __future__ import annotations

import base64
import json
import math
from typing import Annotated, Literal

import rfc8785
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from .canonical import SAFE_INTEGER_MAX
from .wire import exact_int_literal


class TrajectoryError(ValueError):
    pass


class TrajectoryModel(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, strict=True)


def _canonical_base64(value: str) -> str:
    try:
        decoded = base64.b64decode(value, validate=True)
    except (ValueError, TypeError) as exc:
        raise ValueError("invalid Base64") from exc
    if base64.b64encode(decoded).decode("ascii") != value:
        raise ValueError("Base64 must use canonical padded encoding")
    return value


Base64Text = Annotated[str, Field(max_length=64 * 1024**2)]
LargeBase64Text = Annotated[str, Field(max_length=128 * 1024**2)]
SequenceNumber = Annotated[int, Field(ge=0, le=2**31 - 1)]
SmallText = Annotated[str, Field(min_length=1, max_length=256)]
Digest = Annotated[str, Field(pattern=r"^[0-9a-f]{64}$")]


class TokenAlternative(TrajectoryModel):
    token_bytes_b64: Annotated[str, Field(max_length=65_536)]
    token_id: int | str | None
    logprob: float | int | None

    _base64 = field_validator("token_bytes_b64")(_canonical_base64)

    @field_validator("token_id")
    @classmethod
    def validate_token_id(cls, value: int | str | None):
        if isinstance(value, int) and not -SAFE_INTEGER_MAX <= value <= SAFE_INTEGER_MAX:
            raise ValueError("token_id integer is outside the interoperable range")
        return value

    @field_validator("logprob")
    @classmethod
    def validate_logprob(cls, value: float | int | None):
        if value is not None and not math.isfinite(value):
            raise ValueError("logprob must be finite or null")
        return value


class GeneratedToken(TrajectoryModel):
    token_bytes_b64: Annotated[str, Field(max_length=65_536)]
    token_id: int | str | None
    logprob: float | int
    top_logprobs: Annotated[list[TokenAlternative], Field(min_length=5, max_length=5)]

    _base64 = field_validator("token_bytes_b64")(_canonical_base64)

    @field_validator("token_id")
    @classmethod
    def validate_token_id(cls, value: int | str | None):
        if isinstance(value, int) and not -SAFE_INTEGER_MAX <= value <= SAFE_INTEGER_MAX:
            raise ValueError("token_id integer is outside the interoperable range")
        return value

    @field_validator("logprob")
    @classmethod
    def validate_logprob(cls, value: float | int):
        if not math.isfinite(value):
            raise ValueError("chosen-token logprob must be finite")
        return value


class ModelTurn(TrajectoryModel):
    sequence: SequenceNumber
    event_type: Literal["model_turn"]
    request_body_b64: Base64Text
    response_body_b64: LargeBase64Text
    generated_bytes_b64: Base64Text
    reasoning: Annotated[str, Field(min_length=1, max_length=64 * 1024**2)]
    output: Annotated[str, Field(max_length=64 * 1024**2)]
    tokens: Annotated[list[GeneratedToken], Field(min_length=1, max_length=250_000)]

    _base64 = field_validator(
        "request_body_b64", "response_body_b64", "generated_bytes_b64"
    )(_canonical_base64)

    @model_validator(mode="after")
    def validate_generated_bytes(self):
        chosen = b"".join(
            base64.b64decode(token.token_bytes_b64) for token in self.tokens
        )
        if base64.b64encode(chosen).decode("ascii") != self.generated_bytes_b64:
            raise ValueError("chosen tokens do not reproduce generated bytes")
        return self


class ModelFailure(TrajectoryModel):
    sequence: SequenceNumber
    event_type: Literal["model_failure"]
    request_body_b64: Base64Text
    response_body_b64: LargeBase64Text | None
    failure_kind: Literal["transport_error", "http_error", "provider_rejected"]
    status_code: Annotated[int, Field(ge=100, le=599)] | None

    _request_base64 = field_validator("request_body_b64")(_canonical_base64)

    @field_validator("response_body_b64")
    @classmethod
    def validate_response_base64(cls, value: str | None):
        return None if value is None else _canonical_base64(value)

    @model_validator(mode="after")
    def validate_failure(self):
        if self.failure_kind == "transport_error":
            valid = self.response_body_b64 is None and self.status_code is None
        else:
            valid = self.response_body_b64 is not None and self.status_code is not None
        if not valid:
            raise ValueError("failure response fields do not match failure_kind")
        return self


class ToolCall(TrajectoryModel):
    sequence: SequenceNumber
    event_type: Literal["tool_call"]
    call_id: SmallText
    tool_name: SmallText
    input_body_b64: Base64Text

    _base64 = field_validator("input_body_b64")(_canonical_base64)


class ToolResult(TrajectoryModel):
    sequence: SequenceNumber
    event_type: Literal["tool_result"]
    call_id: SmallText
    output_body_b64: LargeBase64Text
    is_error: bool

    _base64 = field_validator("output_body_b64")(_canonical_base64)


class FinalSubmission(TrajectoryModel):
    sequence: SequenceNumber
    event_type: Literal["final_submission"]
    submission_sha256: Digest


TrajectoryEvent = Annotated[
    ModelTurn | ModelFailure | ToolCall | ToolResult | FinalSubmission,
    Field(discriminator="event_type"),
]


class Trajectory(TrajectoryModel):
    schema_version: exact_int_literal(1)
    task_id: Digest
    challenge_id: Annotated[str, Field(min_length=1, max_length=128)]
    miner_hotkey: Annotated[str, Field(min_length=1, max_length=128)]
    submission_sha256: Digest
    harness_name: SmallText
    harness_version: SmallText
    model_provider: SmallText
    model_name: SmallText
    events: Annotated[list[TrajectoryEvent], Field(min_length=4, max_length=100_000)]

    @model_validator(mode="after")
    def validate_events(self):
        if [event.sequence for event in self.events] != list(range(len(self.events))):
            raise ValueError("event sequences must start at zero and be contiguous")
        if not any(isinstance(event, ModelTurn) for event in self.events):
            raise ValueError("trajectory requires a model turn")
        finals = [event for event in self.events if isinstance(event, FinalSubmission)]
        if len(finals) != 1 or self.events[-1] is not finals[0]:
            raise ValueError("trajectory requires one final submission as its last event")
        if finals[0].submission_sha256 != self.submission_sha256:
            raise ValueError("final submission hash does not match trajectory")

        calls: dict[str, int] = {}
        results: dict[str, int] = {}
        for event in self.events:
            if isinstance(event, ToolCall):
                if event.call_id in calls:
                    raise ValueError("tool call IDs must be unique")
                calls[event.call_id] = event.sequence
            elif isinstance(event, ToolResult):
                if event.call_id in results:
                    raise ValueError("tool calls must have exactly one result")
                results[event.call_id] = event.sequence
        if not calls or calls.keys() != results.keys():
            raise ValueError("every tool call must have exactly one result")
        if any(results[call_id] <= sequence for call_id, sequence in calls.items()):
            raise ValueError("tool results must follow their calls")

        alternatives = [
            alternative.logprob
            for event in self.events
            if isinstance(event, ModelTurn)
            for token in event.tokens
            for alternative in token.top_logprobs
        ]
        finite = sum(value is not None and math.isfinite(value) for value in alternatives)
        if finite * 100 < len(alternatives) * 85:
            raise ValueError("at least 85% of alternative logprobs must be finite")
        return self


def serialize_trajectory(trajectory: Trajectory) -> bytes:
    if type(trajectory) is not Trajectory:
        raise TypeError("trajectory must be validated")
    try:
        return rfc8785.dumps(trajectory.model_dump(mode="python"))
    except rfc8785.CanonicalizationError as exc:
        raise TrajectoryError("trajectory cannot be canonicalized") from exc


def parse_trajectory(raw: bytes) -> Trajectory:
    if type(raw) is not bytes or not raw or raw.startswith(b"\xef\xbb\xbf"):
        raise TrajectoryError("trajectory must be nonempty UTF-8 JSON without a BOM")
    try:
        value = json.loads(raw, object_pairs_hook=_unique_object)
        trajectory = Trajectory.model_validate(value)
        if serialize_trajectory(trajectory) != raw:
            raise TrajectoryError("trajectory is not canonical JCS")
        return trajectory
    except TrajectoryError:
        raise
    except (UnicodeDecodeError, json.JSONDecodeError, ValueError, TypeError) as exc:
        raise TrajectoryError("invalid trajectory") from exc


def _unique_object(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise TrajectoryError("trajectory contains a duplicate key")
        result[key] = value
    return result
